#!/usr/bin/env node
// Scans packages/ui/src/{atoms,molecules,organisms} for component files, pulls an
// optional __DOC ... DOC__ (or __DOC_BLOCK ... DOC__ for a full-width demo) comment and
// an optional __PROPS {...} PROPS__ comment out of each one, and regenerates the
// components gallery page from them. A component with no __DOC block falls back to a
// bare `<QUI.Name />`; one with no __PROPS block just gets no props panel.
//
// Run with: pnpm --filter playground run docs:gen
// (also runs automatically before `dev` and `build`, see package.json)
//
// To add a component to the gallery: just add a __DOC block to its source file and
// regenerate — no manual gallery editing needed. To list its prop options in the panel
// beside the demo, add a __PROPS block too:
//
//   /* __PROPS
//   { "size": ["xs", "sm", "md", "lg"], "variant": ["primary", "secondary"] }
//   PROPS__ * /
//
// Keys are prop names; values are either an array of accepted literal values, or the
// string "boolean" for a plain true/false prop.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const outPath = path.join(__dirname, "../src/pages/ComponentsPage.tsx");

const CATEGORIES = [
  { title: "Atoms", dir: path.join(repoRoot, "packages/ui/src/atoms") },
  { title: "Molecules", dir: path.join(repoRoot, "packages/ui/src/molecules") },
  { title: "Organisms", dir: path.join(repoRoot, "packages/ui/src/organisms") },
];

// Captures: [1] = "_BLOCK" or undefined (align hint), [2] = doc content.
const DOC_RE = /__DOC(_BLOCK)?\b([\s\S]*?)DOC__/;
// Captures: [1] = the JSON object body.
const PROPS_RE = /__PROPS\b([\s\S]*?)PROPS__/;

function scanCategory({ dir }) {
  if (!existsSync(dir)) return [];
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".tsx"))
    .sort((a, b) => a.localeCompare(b));

  return files.map((file) => {
    const moduleName = file.replace(/\.tsx$/, "");
    const content = readFileSync(path.join(dir, file), "utf8");
    const docMatch = content.match(DOC_RE);
    const align = docMatch && docMatch[1] ? "block" : "row";
    const demo = docMatch ? docMatch[2].trim() : `<QUI.${moduleName} />`;

    const propsMatch = content.match(PROPS_RE);
    let props = null;
    if (propsMatch) {
      try {
        props = JSON.parse(propsMatch[1].trim());
      } catch (err) {
        console.warn(`Warning: could not parse __PROPS block in ${file}: ${err.message}`);
      }
    }
    return { moduleName, demo, align, props };
  });
}

function renderSection({ moduleName, demo, align, props }) {
  const propsArg = props ? ` props={${JSON.stringify(props)}}` : "";
  return [`          <Section title="${moduleName}" align="${align}"${propsArg}>`, demo, `          </Section>`].join("\n");
}

function renderCategory({ title }, components) {
  return [
    "      <div>",
    `        <h1 className="mb-3 text-base font-semibold">${title}</h1>`,
    '        <div className="flex flex-col gap-6">',
    components.map(renderSection).join("\n"),
    "        </div>",
    "      </div>",
  ].join("\n");
}

const categoriesWithComponents = CATEGORIES.map((cat) => ({ cat, components: scanCategory(cat) })).filter(
  ({ components }) => components.length > 0
);
const categoryBlocks = categoriesWithComponents.map(({ cat, components }) => renderCategory(cat, components));
const totalCount = categoriesWithComponents.reduce((sum, { components }) => sum + components.length, 0);

const file = `// AUTO-GENERATED by apps/playground/scripts/generate-components-page.mjs — do not
// hand-edit this file. Add or change a component's demo by editing the __DOC ... DOC__
// (or __DOC_BLOCK ... DOC__ for a full-width demo) comment in its source file, and its
// prop options by editing the __PROPS {...} PROPS__ comment, then run:
//   pnpm --filter playground run docs:gen
import * as React from "react";
import * as QUI from "@qui/ui";
import * as Icons from "lucide-react";

type PropsSpec = Record<string, ReadonlyArray<string | number> | "boolean">;

function PropsPanel({ props }: { props: PropsSpec }) {
  return (
    <dl className="flex w-56 shrink-0 flex-col gap-3 border-s border-subtle p-4">
      {Object.entries(props).map(([name, values]) => (
        <div key={name} className="flex flex-col gap-1">
          <dt className="font-mono text-caption-md-medium text-primary">{name}</dt>
          <dd className="flex flex-wrap gap-1">
            {values === "boolean"
              ? ["true", "false"].map((v) => (
                  <span key={v} className="rounded-sm bg-layer-3 px-1.5 py-0.5 font-mono text-caption-md-regular text-tertiary">
                    {v}
                  </span>
                ))
              : values.map((v) => (
                  <span key={v} className="rounded-sm bg-layer-3 px-1.5 py-0.5 font-mono text-caption-md-regular text-tertiary">
                    {v}
                  </span>
                ))}
          </dd>
        </div>
      ))}
    </dl>
  );
}

function Section({
  title,
  children,
  align = "row",
  props,
}: {
  title: string;
  children: React.ReactNode;
  align?: "row" | "block";
  props?: PropsSpec;
}) {
  return (
    <section id={\`c-\${title}\`} className="flex scroll-mt-4 flex-col gap-3">
      <h2 className="text-sm font-semibold uppercase tracking-wide text-tertiary">{title}</h2>
      <div className="flex overflow-hidden rounded-lg border border-subtle bg-layer-1">
        <div className={align === "row" ? "flex flex-1 flex-wrap items-center gap-4 p-4" : "flex-1 overflow-hidden"}>{children}</div>
        {props ? <PropsPanel props={props} /> : null}
      </div>
    </section>
  );
}

/** Every component in the gallery, for the playground search. */
export const componentNames = ${JSON.stringify(categoriesWithComponents.flatMap(({ components }) => components.map((c) => c.moduleName)).sort((a, b) => a.localeCompare(b)))};

/** Opening #/components/Badge scrolls to that component section. */
function useScrollToComponent() {
  React.useEffect(() => {
    const scroll = () => {
      const name = decodeURIComponent(window.location.hash.split("/")[2] ?? "");
      const target = name ? document.getElementById(\`c-\${name}\`) : null;
      const main = target?.closest("main");
      if (target && main) main.scrollTop += target.getBoundingClientRect().top - main.getBoundingClientRect().top - 32;
    };
    scroll();
    window.addEventListener("hashchange", scroll);
    return () => window.removeEventListener("hashchange", scroll);
  }, []);
}

export function ComponentsPage() {
  useScrollToComponent();
  return (
    <div className="flex flex-col gap-8">
      <div>
        <h1 className="text-2xl font-semibold text-primary">Components</h1>
        <p className="text-sm text-secondary">Every component and variant, grouped by atomic level.</p>
      </div>

${categoryBlocks.join("\n\n")}
    </div>
  );
}
`;

writeFileSync(outPath, file, "utf8");
console.log(`Generated ${path.relative(repoRoot, outPath)} from ${totalCount} components.`);
